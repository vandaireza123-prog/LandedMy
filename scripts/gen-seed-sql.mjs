// Generates supabase/seed/0001_chapter22.sql from packages/engine/data/chapter22.json
// so the database and the engine's test fixtures share one source of truth.
import { readFileSync, writeFileSync } from "node:fs";

const data = JSON.parse(readFileSync(new URL("../packages/engine/data/chapter22.json", import.meta.url), "utf8"));
const S = data._meta.sources;
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

const out = [];
out.push("-- Generated by scripts/gen-seed-sql.mjs — do not edit by hand. Source: packages/engine/data/chapter22.json");
out.push("begin;");
out.push("delete from sst_rates; delete from excise_lines; delete from tariff_lines;");

for (const l of data.lines) {
  out.push(
    `insert into tariff_lines (hs_code, description, unit, duty_type, duty_value, effective_from, effective_to, source_doc, source_url) values (${q(l.hs_code)}, ${q(l.description)}, 'l', ${q(l.duty.type)}, ${l.duty.value}, '2022-06-01', null, ${q("Customs Duties Order 2022, P.U.(A) 114/2022")}, ${q(S.customs)});`,
  );
  out.push(
    `insert into excise_lines (hs_code, description, excise_type, excise_value, effective_from, effective_to, source_doc, source_url) values (${q(l.hs_code)}, ${q(l.description)}, ${q(l.excise.type)}, ${l.excise.value}, '2022-06-01', '2025-10-31', ${q("Excise Duties Order 2022, P.U.(A) 163/2022")}, ${q(S.excise_2022)});`,
  );
  const v2 = Math.round(l.excise.value * 1.1 * 100) / 100;
  out.push(
    `insert into excise_lines (hs_code, description, excise_type, excise_value, effective_from, effective_to, source_doc, source_url) values (${q(l.hs_code)}, ${q(l.description)}, ${q(l.excise.type)}, ${v2}, '2025-11-01', null, ${q("Budget 2026 +10% alcohol excise (gazetted amendment to be loaded)")}, ${q(S.budget_2026)});`,
  );
  out.push(
    `insert into sst_rates (hs_code, description, rate_pct, effective_from, effective_to, source_doc, source_url) values (${q(l.hs_code)}, ${q(l.description)}, 10, '2018-09-01', null, ${q("Sales Tax Act 2018 — 10% standard rate on imports")}, ${q(S.sst)});`,
  );
}
out.push("commit;");

const target = new URL("../supabase/seed/0001_chapter22.sql", import.meta.url);
writeFileSync(target, out.join("\n") + "\n");
console.log(`wrote ${target.pathname}: ${data.lines.length} HS lines, ${data.lines.length * 2} excise rows`);
